import Foundation

/// Historial del portapapeles: solo texto, solo en memoria, sin duplicados y con tope.
public struct ClipboardHistory: Sendable, Equatable {
  public struct Entry: Sendable, Equatable, Identifiable {
    public var id = UUID()
    public var text: String
    public var date: Date
    public var sourceApp: String?
  }

  public private(set) var entries: [Entry] = []
  public let limit: Int
  public init(limit: Int = 30) { self.limit = limit }

  /// Tipos que marcan los gestores de contraseñas y apps que copian algo pasajero: nunca se guardan.
  public static let privateTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
  ]

  public static func shouldRecord(types: [String]) -> Bool {
    !types.contains { privateTypes.contains($0) }
  }

  /// Agrega un texto; si ya estaba, sube al primer lugar. Devuelve false si se ignoró.
  @discardableResult
  public mutating func add(_ raw: String, sourceApp: String? = nil, date: Date = Date()) -> Bool {
    let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !text.isEmpty, text.count <= 20_000 else { return false }
    entries.removeAll { $0.text == text }
    entries.insert(Entry(text: text, date: date, sourceApp: sourceApp), at: 0)
    if entries.count > limit { entries.removeLast(entries.count - limit) }
    return true
  }

  public mutating func remove(_ id: UUID) { entries.removeAll { $0.id == id } }
  public mutating func clear() { entries.removeAll() }
}

/// Archivos dejados en la bandeja del notch. Se guardan referencias (la ruta), no copias.
public struct ShelfItem: Codable, Sendable, Equatable, Identifiable {
  public var id: UUID
  public var path: String
  public var added: Date
  public init(path: String, added: Date = Date()) {
    id = UUID()
    self.path = path
    self.added = added
  }
  public var url: URL { URL(fileURLWithPath: path) }
  public var name: String { url.lastPathComponent }
  public var exists: Bool { FileManager.default.fileExists(atPath: path) }
}

public final class ShelfStore: @unchecked Sendable {
  public private(set) var items: [ShelfItem] = []
  let file: URL
  public static let limit = 24

  public static var defaultFile: URL {
    FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
      .appendingPathComponent("Faro/bandeja.json")
  }

  public init(file: URL = ShelfStore.defaultFile) {
    self.file = file
    if let data = try? Data(contentsOf: file), let i = try? JSONDecoder().decode([ShelfItem].self, from: data) {
      // Lo que se borró o movió desde la última vez ya no aparece.
      items = i.filter(\.exists)
    }
  }

  /// Agrega rutas (sin repetir); lo nuevo queda primero.
  public func add(_ urls: [URL]) {
    for u in urls.reversed() where u.isFileURL {
      items.removeAll { $0.path == u.path }
      items.insert(ShelfItem(path: u.path), at: 0)
    }
    if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    save()
  }

  public func remove(_ id: UUID) {
    items.removeAll { $0.id == id }
    save()
  }

  public func clear() {
    items.removeAll()
    save()
  }

  func save() {
    try? FileManager.default.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
    if let data = try? JSONEncoder().encode(items) { try? data.write(to: file, options: .atomic) }
  }
}
